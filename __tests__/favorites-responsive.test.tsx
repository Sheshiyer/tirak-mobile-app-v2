import React from 'react';
import { act, fireEvent, render } from '@testing-library/react-native';
import { Dimensions, FlatList, StyleSheet } from 'react-native';
const mockGuide = { id: 'actual-guide', name: 'Canal Guide', location: 'Bangkok', price: 1, services: ['Local walk'], languages: ['en'], rating: 0, reviews: 0, verified: true };
const mockRemove = jest.fn(); const mockToggle = jest.fn();
const mockState = { favorites: ['actual-guide'], favoriteCompanions: { 'actual-guide': mockGuide }, isFavorite: () => true, toggleFavorite: mockToggle };
jest.mock('expo-router', () => ({ router: { push: jest.fn() } }));
jest.mock('expo-image', () => ({ Image: () => null }));
jest.mock('expo-linear-gradient', () => ({ LinearGradient: ({ children }: any) => children }));
jest.mock('lucide-react-native', () => Object.fromEntries(['Heart', 'Search', 'Filter', 'Grid3X3', 'List', 'MapPin', 'Star', 'MessageCircle', 'Camera'].map(name => [name, () => null])));
jest.mock('@/stores/favorites-store', () => ({ useFavoritesStore: Object.assign((select?: any) => select ? select(mockState) : mockState, { getState: () => ({ removeFavorite: mockRemove }) }) }));
jest.mock('@/stores/auth-store', () => ({ useAuthStore: (select: any) => select({ user: { id: 'traveler-test' } }) }));
jest.mock('@tanstack/react-query', () => ({ useQueries: () => [{ isLoading: false }] }));
jest.mock('@/services/api/companion/companion', () => ({ fetchCompanionById: jest.fn() }));
jest.mock('@/utils/demo-mode', () => ({ isDemoModeEnabled: () => false }));
jest.mock('@/utils/companion-display', () => ({ isDemoCompanion: () => false }));
jest.mock('@/components/ui/RadialGradient', () => ({ RadialGradient: require('react-native').View }));
jest.mock('react-i18next', () => ({ useTranslation: () => ({ t: (key: string, options: any) => key === 'companionDetails.fromPrice' ? `From ${options.price}` : key }) }));
import FavoritesScreen from '@/app/(app)/favorites';
const resize = (width: number) => act(() => Dimensions.set({ window: { width, height: 844, scale: 1, fontScale: 1 }, screen: { width, height: 844, scale: 1, fontScale: 1 } }));
beforeEach(() => jest.clearAllMocks());
it('fits the populated saved-guide card after1170→300 resize without remounting the screen, with updated grid geometry', () => {
  const original = Dimensions.get('window'); resize(1170);
  const screen = render(<FavoritesScreen />);
  const cardStyle = () => StyleSheet.flatten(screen.getByTestId('favorite-card-actual-guide').props.style);
  expect(cardStyle().width).toBe(360); expect(screen.UNSAFE_getByType(FlatList).props.numColumns).toBe(3);
  resize(300);
  expect(cardStyle()).toMatchObject({ width: 260, maxWidth: 260, minWidth: 0 });
  expect(cardStyle().width + 40).toBeLessThanOrEqual(300);
  expect(screen.UNSAFE_getByType(FlatList).props.numColumns).toBe(1);
  const heart = screen.getByRole('button', { name: 'Remove Canal Guide from favorites' });
  expect(heart.props.accessibilityState.selected).toBe(true);
  fireEvent.press(heart);
  expect(mockRemove).toHaveBeenCalledTimes(1); expect(mockRemove).toHaveBeenCalledWith('actual-guide');
  expect(mockToggle).not.toHaveBeenCalled();
  screen.unmount(); resize(original.width);
});
it('list view keeps the same labeled removal action and bounded width on a300px phone', () => {
  const original = Dimensions.get('window'); resize(300);
  const screen = render(<FavoritesScreen />);
  fireEvent.press(screen.getByRole('button', { name: 'List view' }));
  expect(StyleSheet.flatten(screen.getByTestId('favorite-card-actual-guide').props.style).width).toBe(260);
  fireEvent.press(screen.getByRole('button', { name: 'Remove Canal Guide from favorites' }));
  expect(mockRemove).toHaveBeenCalledWith('actual-guide'); expect(mockToggle).not.toHaveBeenCalled();
  screen.unmount(); resize(original.width);
});

it('applies validated starting price bounds together with search, and resets without changing saved data', () => {
  const screen = render(<FavoritesScreen />);
  fireEvent.press(screen.getByRole('button', { name: 'Filter saved guides' }));
  fireEvent.changeText(screen.getByLabelText('Minimum saved guide price'), '2');
  fireEvent.changeText(screen.getByLabelText('Maximum saved guide price'), '1');
  expect(screen.getByRole('alert').props.children).toContain('Maximum price');
  expect(screen.getByRole('button', { name: 'Apply favorite price filters' }).props.accessibilityState.disabled).toBe(true);
  fireEvent.press(screen.getByRole('button', { name: 'Apply favorite price filters' }));
  expect(screen.getByTestId('favorite-card-actual-guide')).toBeTruthy();
  fireEvent.changeText(screen.getByLabelText('Maximum saved guide price'), '');
  fireEvent.press(screen.getByRole('button', { name: 'Apply favorite price filters' }));
  expect(screen.queryByTestId('favorite-card-actual-guide')).toBeNull();
  expect(screen.getByText('No saved guides match these prices')).toBeTruthy();
  expect(screen.queryByText('favorites.noFavorites')).toBeNull();
  fireEvent.press(screen.getByRole('button', { name: 'Clear filters' }));
  expect(screen.getByTestId('favorite-card-actual-guide')).toBeTruthy();
  fireEvent.press(screen.getByRole('button', { name: 'Filter saved guides' }));
  fireEvent.changeText(screen.getByLabelText('Maximum saved guide price'), '1');
  fireEvent.press(screen.getByRole('button', { name: 'Apply favorite price filters' }));
  fireEvent.changeText(screen.getByPlaceholderText('favorites.searchFavorites'), 'unmatched');
  expect(screen.queryByTestId('favorite-card-actual-guide')).toBeNull();
  fireEvent.press(screen.getByRole('button', { name: 'Clear filters' }));
  expect(screen.getByTestId('favorite-card-actual-guide')).toBeTruthy();
  fireEvent.press(screen.getByRole('button', { name: 'Filter saved guides' }));
  expect(screen.getByLabelText('Maximum saved guide price').props.value).toBe('');
  fireEvent.changeText(screen.getByLabelText('Minimum saved guide price'), '-1');
  expect(screen.getByRole('alert').props.children).toContain('valid price');
  fireEvent.press(screen.getByRole('button', { name: 'Reset favorite price filters' }));
  expect(screen.getByLabelText('Minimum saved guide price').props.value).toBe('');
  expect(screen.queryByRole('alert')).toBeNull();
  expect(mockRemove).not.toHaveBeenCalled(); expect(mockToggle).not.toHaveBeenCalled();
  expect(mockState.favorites).toEqual(['actual-guide']); screen.unmount();
});
